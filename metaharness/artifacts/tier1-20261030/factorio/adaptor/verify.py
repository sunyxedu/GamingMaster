"""Real-engine acceptance checks. Privileged fixtures are test-only, never game actions."""
import json
import random
import time
from pathlib import Path
from game import make_game, ROOT, SEEDS


def run():
    report = {"engine": "2.0.72", "checks": {}}
    g = make_game()
    try:
        o = g.reset(SEEDS['dev'][0])
        pristine = o
        assert o['charged_ticks'] == 0 and o['paused'] and g.score == 0
        assert len(json.dumps(o).encode()) < 200000
        report['checks']['initial_bytes'] = len(json.dumps(o).encode())
        # Query the actual server across sixty seconds, not merely the Python cache.
        before = g.rcon.request(method='observe')
        print('Checking 60-second paused stability...', flush=True)
        time.sleep(30)
        time.sleep(30)
        assert g.rcon.request(method='observe') == before
        report['checks']['paused_60_seconds'] = True
        coal = next(r[0] for r in o['resources'] if r[1] == 'coal')
        iron = next(r[0] for r in o['resources'] if r[1] == 'iron-ore')
        o = g.step(f'mine_resource {coal} 10; mine_resource {iron} 20; place stone-furnace 0 0')
        assert not g.invalid_reason, g.info()
        furnace = o['results'][2]['id']
        o = g.step('wait')
        assert o['stock']['coal'] == 10 and o['stock']['iron-ore'] == 20
        assert o['production'] == {} and g.score == 0
        o = g.step(f'insert {furnace} fuel coal 10; insert {furnace} source iron-ore 20')
        assert o['production']['iron-plate'] == 9, o
        assert abs(g.score - .09) < 1e-10
        report['checks']['furnace_30_seconds'] = {'plates': 9, 'score': g.score}
        o = g.step(f'extract {furnace} result iron-plate 9; handcraft iron-gear-wheel 2')
        assert o['manual_output']['iron-gear-wheel'] == 2
        assert o['production'].get('iron-gear-wheel', 0) == 0
        assert o['transfers'] == 39
        report['checks']['manual_and_transfer_exclusion'] = True
        # Re-delivering an acknowledged step must not execute it again.
        snapshot = g.rcon.request(method='observe')
        response = g.rcon.request(method='step', turn=o['turn'], actions=[['wait']])
        assert response['duplicate'] and g.rcon.request(method='observe') == snapshot
        report['checks']['duplicate_step'] = True
        # Invalid syntax does not change time/stock; illegal valid actions still cost a turn.
        tick = o['tick']
        o = g.step({'evil': 'action'})
        assert o['tick'] == tick and not g.invalid_reason
        o = g.step('place stone-furnace 0 0; insert 9999999 fuel coal 3; handcraft rocket-part 1')
        assert o['tick'] == tick + 1800 and all(not r['ok'] for r in o['results'])
        report['checks']['illegal_actions_safe'] = True
        # Obtain diagnostics using trusted RCON, unavailable through the action grammar.
        g.rcon.command('/sc rcon.print("fixture-console-ready")')
        g.rcon.command('/sc rcon.print("fixture-console-ready")')
        fixture = '''local s=game.surfaces[1];local f=game.forces.player;
        f.technologies['steam-power'].researched=true;f.technologies.electronics.researched=true;f.technologies['automation-science-pack'].researched=true;f.technologies.automation.researched=true;
        local power=s.create_entity{name='electric-energy-interface',position={0,4},force=f};
        power.electric_buffer_size=1000000000;power.power_production=10000000;power.energy=1000000000;
        s.create_entity{name='substation',position={0,0},force=f};
        local a=s.create_entity{name='assembling-machine-1',position={-4,0},force=f};
        a.set_recipe('automation-science-pack');a.insert{name='iron-gear-wheel',count=10};a.insert{name='copper-plate',count=10};
        local lab=s.create_entity{name='lab',position={4,0},force=f};lab.insert{name='automation-science-pack',count=5};
        f.add_research('logistics');rcon.print('fixture-created')'''
        reply = g.rcon.command('/sc ' + fixture.replace('\n', ' '))
        assert 'fixture-created' in reply, reply
        o = g.step('wait')
        assert not g.invalid_reason, g.info()
        assert o['production']['automation-science-pack'] > 0, o['production']
        assert o['consumption']['automation-science-pack'] > 0, o['consumption']
        assert o['lab_consumption']['automation-science-pack'] == o['consumption']['automation-science-pack']
        assert o['research']['progress'] > 0, o['research']
        report['checks']['powered_assembler_and_lab'] = {k: o[k] for k in ['production', 'consumption', 'lab_consumption', 'research', 'score']}
        print('Production and research fixtures passed.', flush=True)
        # Every seed family is generated by the real engine; verify physical distinction.
        physical = []
        fingerprints = {}
        for key, seeds in SEEDS.items():
            for seed in seeds:
                o = g.reset(seed)
                assert not g.invalid_reason and o['charged_ticks'] == 0
                assert all(p['initial_amount'] > 200000 for p in o['patches'])
                assert len(o['trees']) > 0 and o['pump_site']
                physical.append(json.dumps([o['patches'], o['water_rows']], sort_keys=True))
                import hashlib
                fingerprints[seed] = hashlib.sha256(physical[-1].encode()).hexdigest()
                print('Seed checked:', key, seed, flush=True)
        assert len(set(physical)) == len(physical)
        report['checks']['distinct_feasible_seeds'] = len(physical)
        report['seed_layout_sha256'] = fingerprints
        o = g.reset(SEEDS['dev'][0])
        assert pristine == o
        report['checks']['deterministic_full_reset'] = True
        rng = random.Random(54)
        for _ in range(8):
            a = rng.choice(['wait', f'mine_resource {coal} 3', 'handcraft iron-gear-wheel 1', 'place wooden-chest 5 5', 'mine_tree -1'])
            o = g.step(a)
            assert not g.invalid_reason, g.info()
            assert o['charged_ticks'] == 1800 * o['turn']
            json.dumps(o, allow_nan=False)
        report['checks']['random_actions'] = {'turn': o['turn'], 'score': g.score, 'stock': o['stock'], 'manual_output': o['manual_output']}
        # Unexpected process death must invalidate the trial, not return a valid zero.
        g.process.kill();g.process.wait()
        assert g.info()['valid_trial'] is False
        report['checks']['crash_invalidates'] = True
    finally:
        g.close();g.close()
    (ROOT / 'runtime' / 'verification.json').write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    run()
